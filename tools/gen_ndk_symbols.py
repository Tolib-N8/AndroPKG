#!/usr/bin/env python3
"""Generates the andropkg NDK layer's symbol tables (ndk-libs/system.c includes them).

  gen_ndk_symbols.py <ndk-libs dir> <out dir>
    ndk_symbols.inc: kSystemSymbols (every symbol of the NDK system libraries, sorted),
                     kDirectSymbols (ndk-libs/direct.txt, sorted), kSystemLibs (sonames)
    ndk_traps.inc:   NDK_TRAPS trap stubs and their table
"""
import os, sys

src, out = sys.argv[1], sys.argv[2]
os.makedirs(out, exist_ok=True)
syms, libs = set(), []
symdir = os.path.join(src, "symbols")
for f in sorted(os.listdir(symdir)):
    if not f.endswith(".txt"):
        continue
    libs.append(f[:-4] + ".so")
    for line in open(os.path.join(symdir, f)):
        parts = line.split()
        if len(parts) == 2:
            syms.add(parts[1])
# Libraries an app may name in DT_NEEDED that are part of the platform too.
libs += ["libGLESv3.so", "libstdc++.so", "libvulkan.so", "libbinder_ndk.so", "libicu.so",
         "libneuralnetworks.so", "libnativehelper.so", "libOpenMAXAL.so"]
direct = set()
for line in open(os.path.join(src, "direct.txt")):
    line = line.split("#", 1)[0]
    direct.update(line.split())

def arr(name, items):
    body = ",\n".join('    "%s"' % s for s in sorted(set(items)))
    return "static const char *const %s[] = {\n%s\n};\n" % (name, body)

with open(os.path.join(out, "ndk_symbols.inc"), "w") as o:
    o.write("// Generated by tools/gen_ndk_symbols.py — do not edit.\n")
    o.write(arr("kSystemSymbols", syms))
    o.write(arr("kDirectSymbols", direct))
    o.write(arr("kSystemLibs", libs))

with open(os.path.join(out, "ndk_traps.inc"), "w") as o:
    o.write("// Generated by tools/gen_ndk_symbols.py — do not edit.\n")
    n = 2048
    for i in range(n):
        o.write("static long trap_%d(void) { return trap_hit(%d); }\n" % (i, i))
    o.write("static long (*const kTraps[%d])(void) = {\n" % n)
    o.write(",\n".join("    trap_%d" % i for i in range(n)))
    o.write("\n};\n")
