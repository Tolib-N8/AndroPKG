#!/usr/bin/env python3
"""Stubs for the GL entry points the framework's GL JNI names but the platform's GL lacks.

  gen_gl_stubs.py <out.c> <redirect.h> <ios|macos> <sdk tbd>... -- <sources>...

iOS OpenGL ES lacks some GLES 1.x extensions (OES_query_matrix, texture_cube_map, ...); the macOS
GLES stand-in (GLES 2.0 on OpenGL 2.1, runtime/opengl/egl.m) lacks GLES 1.x fixed-point and some
GLES 3.0 entry points. libandropkg_gl must still link and load: each stub logs, returns 0.
"""
import re, sys

out, redirect, platform = sys.argv[1], sys.argv[2], sys.argv[3]
sep = sys.argv.index("--")
tbds, srcs = sys.argv[4:sep], sys.argv[sep + 1:]
have = set()
for t in tbds:
    have.update(re.findall(r"\b_(gl[A-Za-z0-9_]+)\b", open(t).read()))
rtext = open(redirect).read()  # the platform's branch of gl_redirect.h
rtext = re.sub(r"#if TARGET_OS_IPHONE(.*?)#else(.*?)#endif", lambda m: m.group(1 if platform == "ios" else 2), rtext,
               flags=re.S)
redirected = set(re.findall(r"#define (gl\w+) bionic_", rtext))
used = set()
for s in srcs:
    text = open(s, errors="replace").read()
    used.update(re.findall(r"(?<![\w.])(gl[A-Z]\w*)\s*\(", text))
    used.update(re.findall(r"#define\s+gl\w+\s+(gl\w+)", text))  # #define glX glXOES
missing = sorted(used - have - redirected)
with open(out, "w") as o:
    o.write("// Generated by tools/gen_mac_gl_stubs.py — do not edit.\n#include <android/log.h>\n")
    o.write("static long missing(const char *n) {\n"
            "    __android_log_print(ANDROID_LOG_WARN, \"andropkg-gl\", \"%s: not in the platform's OpenGL (ES)\", n);\n"
            "    return 0;\n}\n")
    for f in missing:
        o.write('__attribute__((visibility("hidden"))) long %s(void) { return missing("%s"); }\n' % (f, f))
print("gen_gl_stubs: %d stubs" % len(missing))
