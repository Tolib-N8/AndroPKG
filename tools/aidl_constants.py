#!/usr/bin/env python3
"""Generates the C++ header for a constants-only AIDL interface (what `aidl --lang=cpp` emits
for `const int` members), e.g. android/os/IInputConstants.aidl -> IInputConstants.h.

    aidl_constants.py <in.aidl> <out.h>
"""
import re
import sys

src, out = sys.argv[1:]
text = re.sub(r"/\*.*?\*/", "", open(src).read(), flags=re.S)
text = re.sub(r"//[^\n]*", "", text)
pkg = re.search(r"package\s+([\w.]+)\s*;", text).group(1)
name = re.search(r"interface\s+(\w+)", text).group(1)
consts = re.findall(r"const\s+(int|long)\s+(\w+)\s*=\s*([^;]+);", text)
ns = pkg.split(".")
lines = ["// Generated by andropkg tools/aidl_constants.py from " + src.split("/")[-1] + ". Do not edit.",
         "#pragma once", "#include <cstdint>", ""]
lines += [f"namespace {n} {{" for n in ns]
lines.append(f"class {name} {{\n public:")
for t, k, v in consts:
    ctype = "int32_t" if t == "int" else "int64_t"
    lines.append(f"  static constexpr {ctype} {k} = {v.strip()};")
lines.append("};")
lines += ["}" for _ in ns]
open(out, "w").write("\n".join(lines) + "\n")
