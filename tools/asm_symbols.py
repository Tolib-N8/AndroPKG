#!/usr/bin/env python3
"""asm_symbols.py <out.h> <obj>... — emits `#define sym _sym` for every global symbol that
ELF-flavoured assembly defines or references.

ELF has no symbol prefix; Mach-O prefixes C-level symbols with '_'. Phase 1 assembles the
ported sources unmodified; this script reads their symbol tables (nm), and phase 2 re-assembles
with this header force-included, so `bl artFoo` becomes `bl _artFoo`, `ENTRY art_quick_x`
defines `_art_quick_x`, and C++-mangled `_ZN3art...` becomes `__ZN3art...`.
"""
import subprocess
import sys

out, objs = sys.argv[1], sys.argv[2:]
syms = set()
for o in objs:
    res = subprocess.run(["nm", "-gj", o], check=True, stdout=subprocess.PIPE, text=True).stdout
    # -g: external (defined global + undefined); -j: names only
    syms.update(s.strip() for s in res.splitlines() if s.strip())
lines = ["// Generated by tools/asm_symbols.py — Mach-O names for ELF-assembly symbols.", "#pragma once"]
lines += [f"#define {s} _{s}" for s in sorted(syms) if s.replace("_", "a").replace("$", "a").isalnum()]
with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
